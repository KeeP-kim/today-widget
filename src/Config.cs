        /// <summary>조각 창 배율. 범위를 벗어나거나 값이 없으면 NaN(= 카드 배율 따르기).</summary>
        private static double PanelScale(double v)
        {
            if (double.IsNaN(v)) return double.NaN;
            if (v < MinPanelScale || v > MaxScale) return double.NaN;
            return v;
        }

        /// <summary>배율을 허용 범위로 자른다. 범위 밖·NaN 이면 1.0.</summary>
        internal static double ScaleOrDefault(double v)
        {
            if (double.IsNaN(v) || double.IsInfinity(v)) return 1.0;
            return v < MinScale ? MinScale : v > MaxScale ? MaxScale : v;
        }
        /// <summary>
        /// 설정 문자열에서 그 품목의 왕복 비용을 %로 꺼낸다. 없으면 0.
        /// 값이 없으면 문턱은 종전대로다 - 없는 비용을 지어내 채우지 않는다.
        /// </summary>
        internal static double CostOf(string setting, string key)
        {
            if (string.IsNullOrEmpty(setting) || string.IsNullOrEmpty(key)) return 0;
            foreach (string part in setting.Split(new[] { ',', ';', '\n' }, StringSplitOptions.RemoveEmptyEntries))
            {
                int eq = part.IndexOf('=');
                if (eq <= 0) continue;
                if (part.Substring(0, eq).Trim() != key) continue;
                double v;
                if (!double.TryParse(part.Substring(eq + 1).Trim(), NumberStyles.Float, CultureInfo.InvariantCulture, out v)) return 0;
                // 말이 되는 범위 밖이면 무시한다. 오타 하나로 예측이 통째로 침묵하면 안 된다.
                return double.IsNaN(v) || v < 0 || v > 10 ? 0 : v;
            }
            return 0;
        }

