        ///
        /// ★ '프로그램과 같은 드라이브' 로 좁히면 안 된다 ★
        ///   처음에 그렇게 썼는데, 바탕화면과 시작 메뉴는 언제나 시스템 드라이브(C:)에 있다.
        ///   위젯을 D: 에 두고 쓰는 지금 설정에서는 가장 흔한 바로가기가 통째로,
        ///   아무 말 없이 사라진다. 막아야 할 것은 '남의 컴퓨터' 지 '다른 드라이브' 가 아니다.
        /// </summary>
        private static string LocalOnly(string p)
        {
            if (string.IsNullOrEmpty(p)) return null;
            if (p.StartsWith("\\\\", StringComparison.Ordinal) || p.StartsWith("//", StringComparison.Ordinal)) return null;
            try {
                string root = System.IO.Path.GetPathRoot(p);
                if (string.IsNullOrEmpty(root)) return null;
                return new DriveInfo(root).DriveType == DriveType.Fixed ? p : null;
            } catch (ArgumentException) { return null; } catch (IOException) { return null; }
              catch (UnauthorizedAccessException) { return null; }
        }

        /// <summary>
        /// 이 판의 성적이 어느 '잣대' 아래에서 나온 것인가.
        ///
        /// ★ 판올림과 잣대 변경은 다르다 ★
        ///   성적표를 판별로 묶으면 판올림 한 번에 표본이 쪼개진다. 그런데 날씨 창을 막거나
        ///   로그인을 고쳐서 올린 판은 채점 방식을 하나도 안 건드린다. 그런 것까지 갈라 놓으면
        ///   표본이 영영 안 쌓인다 - 실측으로 예보 72건이 판 11개에 흩어져 가장 큰 칸이 12건이었고,
        ///   60%를 주장하는 데 필요한 것은 97건이다.
        ///   갈라야 하는 것은 ScoringRevisions 에 오른 판뿐이다. 그 목록은 이미 관리하고 있다.
        ///
        ///   그 판보다 이르거나 같은 마지막 잣대 판을 돌려준다. 모르는 판(빈 값·오타)은
        ///   그대로 돌려준다 - 아는 척해서 남의 칸에 섞는 것보다 제 칸에 혼자 있는 편이 낫다.
        /// </summary>
        public static string ScoringEra(string version)
        {
            double v = VersionOf(version);
            if (v <= 0) return string.IsNullOrEmpty(version) ? "?" : version;
            string era = null;
            foreach (string r in ScoringRevisions)
            {
                double rv = VersionOf(r);
                if (rv > 0 && rv <= v) era = r;
            }
            // 첫 잣대 판보다 이른 기록은 그 시절끼리 한 칸으로 둔다.
            return era ?? "~" + ScoringRevisions[0];
        }

        private static double VersionOf(string s)
        {
            if (string.IsNullOrEmpty(s)) return 0;
            double v;
            if (double.TryParse(s, NumberStyles.Any, CultureInfo.InvariantCulture, out v)) return v;
            return 0;
        }

        private static double Clamp(double v, double lo, double hi, double fallback)
        {
            if (double.IsNaN(v) || double.IsInfinity(v)) return fallback;
            if (v < lo) return lo;
            if (v > hi) return hi;
            return v;
        }

        /// <summary>표시용 문자열 정리 - 길이 제한 + 제어문자 제거.</summary>
        /// <summary>
        /// https 주소만 통과시킨다. 설정 파일이 오염되더라도 엉뚱한 곳을 부르지 않게 한 겹 더 두는 것으로,
        /// Net.GetJsonAsync 안에도 같은 검사가 있다.
        /// </summary>
        private static string SafeHttpsUrl(string s)
        {
            s = Sanitize(s, 300);
            if (string.IsNullOrEmpty(s)) return null;
            Uri u;
            if (!Uri.TryCreate(s, UriKind.Absolute, out u)) return null;
            if (u.Scheme != Uri.UriSchemeHttps) return null;
            if (!string.IsNullOrEmpty(u.UserInfo)) return null;   // user@host 형태 차단
            return s;
        }

        /// <summary>받은 버전이 지금 도는 버전보다 높은가. 0.49 -> 0.50 처럼 소수 두 자리 기준이다.</summary>
        public static bool IsNewer(string version)
        {
            double v = VersionOf(version);
            if (v <= 0) return false;
            // 부동소수 오차로 같은 버전이 새 것처럼 보이지 않게 여유를 둔다
            return v > VersionOf(AppVersion) + 0.0001;
        }
        private static string Sanitize(string s, int maxLen)
        {
            if (string.IsNullOrEmpty(s)) return null;
            var sb = new StringBuilder(Math.Min(s.Length, maxLen));
            foreach (char c in s)
            {
                if (c < ' ') continue;
                sb.Append(c);
                if (sb.Length >= maxLen) break;
            }
            string r = sb.ToString().Trim();
            return r.Length == 0 ? null : r;
        }

        /// <summary>숫자만 남긴다. URL에 끼워 넣는 값이므로 엄격하게 거른다.</summary>
        private static string Digits(string s, int maxLen)
        {
            if (string.IsNullOrEmpty(s)) return null;
            var sb = new StringBuilder(maxLen);
            foreach (char c in s)
            {
                if (c < '0' || c > '9') continue;
                sb.Append(c);
                if (sb.Length >= maxLen) break;
            }
            return sb.Length == 0 ? null : sb.ToString();
        }
